/**
 * 受力分解台的实时计算。
 * C_L 用转速参数 S = ωR/v 的饱和曲线：C_L = CLmax·S/(S+0.25)，
 * 与文献"升力系数随转速参数增长并饱和"的形态一致。
 */
export function forceCalc(cfg, v, rpm) {
  const A = cfg.areaOverride ?? Math.PI * cfg.R * cfg.R
  const omega = (rpm * 2 * Math.PI) / 60
  const S = omega * cfg.R / Math.max(v, 0.5)
  const CL = cfg.CLmax > 0 ? cfg.CLmax * (S / (S + 0.25)) : 0
  const fg = cfg.m * 9.81
  const fd = 0.5 * RHO * cfg.CD * A * v * v
  const fm = 0.5 * RHO * CL * A * v * v
  return {
    fg, fd, fm, CL, S, area: A,
    // 与重力的倍数（教学读数）
    fdX: fd / fg, fmX: fm / fg,
    // 侧向偏移示例：假设侧向力近似恒定，飞行 cfg.driftT 秒（各运动的真实飞行时间口径）
    drift: (fm / cfg.m) * 0.5 * cfg.driftT * cfg.driftT
  }
}

